export function templateScript(topicId: string, size: number): Script {
  const found = findTopic(topicId);
  const title = found?.topic.title ?? "テーマ";
  const { lines, conclusion } = core(found?.type.id ?? "business", title);
  const memberSay: L[] = [
    [4, 2, "別の角度からも考えたいです。利用者の本音を想像すると、新しい案が出そうです。"],
    [5, 3, "その案、具体的に誰がどう動くのかまで詰めると強くなりそうです。"],
  ];
  const out: ScriptLine[] = [];
  for (const [s, p, t, note, tip] of lines) {
    // 人数が足りない場合、メンバーの発言を他の役割に振り替える
    const speaker = s < size ? s : s === 4 ? 2 : 3;
    out.push({ s: speaker, p, t, ...(note ? { note } : {}), ...(tip ? { tip } : {}) });
  }
  if (size >= 5) {
    const idx = out.findIndex((l) => l.p === 3);
    for (const [s, p, t] of memberSay) {
      if (s < size) out.splice(p === 2 ? idx : idx + 2, 0, { s, p, t });
    }
  }
  return { topicId, size, lines: out, conclusion, source: "template" };
}
